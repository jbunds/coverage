//go:embed html/* css/* img/*
var embeddedFiles embed.FS

// stickyWriter is a wrapper interface used to enable sequential string writing with deferred error handling.
type stickyWriter interface {
	io.Writer
	write(string)
	err() error
}

// errorWriter tracks the first encountered I/O failure to allow multiple sequential writes without repetitive inline error checking.
type errorWriter struct {
	w        io.Writer
	e        error
	useColor bool
}

// write performs a sticky-error write.
func (w *errorWriter) write(s string) {
	if w.e != nil { return }
	_, w.e = io.WriteString(w.w, s)
}

// write performs a sticky-error write that optionally wraps the provided string in ANSI color codes.
func (w *errorWriter) writeColor(s, color string) {
	if w.e != nil { return }
	if !w.useColor {
		w.write(s)
		return
	}
	w.write(color)
	w.write(s)
	w.write("\033[0m") // reset attributes, styles, and colors to defaults
}

// err returns the first I/O failure encountered during multiple sequential write operations.
func (w *errorWriter) err() error { return w.e }

// Write satisfies the io.Writer interface, but is otherwise unused.
func (w *errorWriter) Write(p []byte) (int, error) {
	if w.e != nil { return 0, w.e }
	return w.w.Write(p)
}

func newErrorWriter(w io.Writer) *errorWriter {
	return &errorWriter{
		w:        w,
		useColor: isTerm(w),
	}
}

// coverage tracks per-file coverage.
type coverage struct {
	covered int64
	total   int64
}

// profileBlock maps a coverage profile range to its absolute byte offsets in the source file.
type profileBlock struct {
	startOffset, endOffset, count int
}

// workUnit represents a unit of work to be performed: the generation of an HTML file for a Go source file's coverage profile.
type workUnit struct {
	profile *cover.Profile
	outPath string
}

// reportGenerator orchestrates the generation of the HTML report.
type reportGenerator struct {
	fsys            writeFS             // wrapper around the os functions used herein
	embeddedFiles   fs.FS               // templates and static files referenced by the generated HTML
	modFile         string              // path to go.mod
	modName         string              // module name
	repoURL         string              // repository URL written to the repo link in index.html template via .ModURL
	outRoot         string              // value of the -path flag
	profilePath     string              // value of the -coverprofile flag
	profiles        []*cover.Profile    // coverage profiles generated by `go tool cover`
	pkgDirCache     map[string]string   // pkgDirCache maps canonical Go packages to their respective paths on disk
	cov             map[string]coverage // per-file coverage stats
	totalCovered    atomic.Int64        // module-wide total number of statements covered
	totalStatements atomic.Int64        // module-wide total number of statements
	staticFiles     []string            // static CSS, HTML, and image files required by the generated HTML
	styleCSSFile    string              // name of the CSS file used by index.html and generated source HTML files
}

func main() {
	os.Exit(run())
}

func run() int {
	ctx, stop := signal.NotifyContext(context.Background(),
		os.Interrupt,    // ctrl+c
		syscall.SIGTERM, // standard kill signal
		syscall.SIGHUP,  // terminal closed, SSH disconnection, etc
	)
	defer stop()

	var (
		indexHTMLFile = "html/index.html" // embedded template (.ModName, .ModURL, .TreeHTML)
		staticFiles   = []string{         // static files
			"css/style.css",
			"css/tree.css",
			"html/code.html",
			"img/favicon.ico",
			"img/go-blue-gradient.svg",
		}
	)

	goModFile, profilePath, outRoot, err := flags(flag.CommandLine, filterArgs(os.Args[1:]))
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot parse flags: %v\n", err)
		return 1
	}

	// TODO(jbunds): (maybe?) add an adapter to handle both legacy textfmt and binary coverage profiles
	profiles, err := cover.ParseProfiles(profilePath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot parse coverage profile file: %v\n", err)
		return 2
	}

	fmt.Fprintf(os.Stderr, "processing %d source files...", len(profiles))
	if !isTerm(os.Stderr) { fmt.Println() } // nolint:forbidigo

	repGen := &reportGenerator{
		fsys:          &localFS{},
		modFile:       filepath.Clean(goModFile),
		outRoot:       filepath.Clean(outRoot),
		profilePath:   filepath.Clean(profilePath),
		profiles:      profiles,
		embeddedFiles: embeddedFiles,
		staticFiles:   staticFiles,
		styleCSSFile:  "style.css",
	}

	if err := repGen.getModName(ctx, goModFile); err != nil { // sets repGen.modName
		fmt.Fprintf(os.Stderr, "cannot determine module name: %v\n", err)
		return 3
	}

	if err := repGen.getRemoteURL(ctx, goModFile, new(realRunner)); err != nil { // sets repGen.repoURL
		fmt.Fprintf(os.Stderr, "cannot determine remote URL: %v\n", err)
		return 4
	}

	if err := repGen.primePkgDirCache(ctx, packages.Load); err != nil { // sets repGen.pkgDirCache
		fmt.Fprintf(os.Stderr, "cannot prime package directory cache: %v\n", err)
		return 5
	}

	if err := repGen.writeCovHTMLFiles(ctx, os.Stderr); err != nil { // sets repGen.cov
		fmt.Fprintf(os.Stderr, "cannot write HTML coverage files: %v\n", err)
		return 6
	}

	tb := &treeBuilder{
		fsys:    &localFS{},
		modName: repGen.modName,
		outRoot: filepath.Clean(outRoot),
		cov:     repGen.cov,
	}

	var treeHTML string
	if treeHTML, err = tb.buildTreeHTML(ctx, os.Stderr); err != nil {
		fmt.Fprintf(os.Stderr, "cannot build tree HTML: %v\n", err)
		return 8
	}

	if err := repGen.writeIndexHTML(ctx, indexHTMLFile, treeHTML); err != nil { // requires repGen.modName, repGen.repoURL
		fmt.Fprintf(os.Stderr, "cannot write %q: %v\n", indexHTMLFile, err)
		return 7
	}

	if err := repGen.writeStaticFiles(ctx); err != nil {
		fmt.Fprintf(os.Stderr, "cannot write static files: %v\n", err)
		return 9
	}

	if err := repGen.printCoverage(ctx, os.Stdout); err != nil { // requires repGen.cov
		fmt.Fprintf(os.Stderr, "cannot print per-file coverage figures: %v\n", err)
		return 10
	}

	return 0
}

// getModName reads the repo's root go.mod file to determine the name of the Go module.
func (rg *reportGenerator) getModName(ctx context.Context, goModFile string) error {
	if err := ctx.Err(); err != nil { return err }

	goMod, err := rg.fsys.ReadFile(ctx, goModFile)
	if err != nil                          { return fmt.Errorf("cannot read %q: %w",  goModFile, err) }
	modFile, err := modfile.Parse(goModFile, goMod, nil)
	if err != nil || modFile.Module == nil { return fmt.Errorf("cannot parse %q: %w", goModFile, err) }
	rg.modName = modFile.Module.Mod.Path

	return nil
}

// getRepoURL converts a remote URL to an HTTP URL for subsequent use in writeIndexHTML.
func (rg *reportGenerator) getRemoteURL(ctx context.Context, goModFile string, runner runner) error {
	if err := ctx.Err(); err != nil { return err }

	// handles custom import paths (vanity URLs) resolved via Go's HTML <meta> tag discovery mechanism:
	//
	//   <meta name="go-import" content="import-prefix vcs repo-root subdir">
	//
	// see also https://pkg.go.dev/cmd/go#hdr-Fully_qualified_import_paths

	var stdout, stderr bytes.Buffer

	cmd       := exec.CommandContext(ctx, "git", "config", "--get", "remote.origin.url")
	cmd.Dir    = filepath.Dir(goModFile)
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr

	if err := runner.Run(cmd); err != nil {
		rg.repoURL = "https://" + rg.modName // fallback to modName
		return nil
	}

	remoteURL := strings.TrimSpace(stdout.String())

	if idx := strings.Index(remoteURL, "@"); idx != -1 {
		remoteURL = remoteURL[idx + 1:]
	}

	remoteURL = strings.TrimPrefix(remoteURL, "ssh://")
	remoteURL = strings.TrimPrefix(remoteURL, "git://")

	if !strings.HasPrefix(remoteURL, "http://" ) &&
	   !strings.HasPrefix(remoteURL, "https://") {
		 remoteURL = "https://" + strings.Replace(remoteURL, ":", "/", 1)
	}

	u, err  := url.Parse(remoteURL)
	if err  != nil { return err }

	httpURL := fmt.Sprintf("https://%s%s", u.Host, u.Path)
	httpURL  = strings.TrimSuffix(httpURL, ".git")
	httpURL  = strings.TrimSuffix(httpURL, "/")

	rg.repoURL = httpURL

	return nil
}

// getAllPkgPaths extracts all unique package paths from the coverage profile file for subsequent use in primePkgDirCache.
func (rg *reportGenerator) getAllPkgPaths(ctx context.Context) ([]string, error) {
	if err := ctx.Err(); err != nil { return nil, err }

	f, err := rg.fsys.OpenWithContext(ctx, filepath.Clean(rg.profilePath))
	if err != nil { return nil, err }

	defer func() {
		closeErr := f.Close()
		if err == nil { err = closeErr }
	}()

	pkgSet  := make(map[string]struct{})
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "mode:") { continue }

		parts := strings.Split(line, ":")
		if len(parts) < 2 { continue }

		pkgSet[filepath.Dir(parts[0])] = struct{}{}
	}

	allPaths := make([]string, 0, len(pkgSet))
	for p := range pkgSet { allPaths = append(allPaths, p) }

	return allPaths, scanner.Err()
}

// primePkgDirCache primes rg.pkgDirCache for subsequent use in buildCovHTML.
func (rg *reportGenerator) primePkgDirCache(ctx context.Context, pkgLoader pkgLoader) error {
	if err := ctx.Err(); err != nil { return err }

	allPkgPaths, err := rg.getAllPkgPaths(ctx)
	if err != nil { return err }

	cfg := &packages.Config{
		Mode:  packages.NeedFiles | packages.NeedModule | packages.NeedName,
		Tests: false,
		Dir:   filepath.Dir(rg.modFile),
	}
	pkgs, err := pkgLoader(cfg, allPkgPaths...)
	if err != nil { return err }

	cache := make(map[string]string)

	for _, pkg := range pkgs {
		if len(pkg.GoFiles) > 0 {
			cache[pkg.PkgPath] = filepath.Dir(pkg.GoFiles[0])
		}
	}

	rg.pkgDirCache = cache

	return nil
}

// writeCovHTMLFiles calculates per-file coverage percentages and writes a *.go.html file for each Go source file listed in the coverage profile file.
func (rg *reportGenerator) writeCovHTMLFiles(ctx context.Context, progressOutput io.Writer) error {
	if err := ctx.Err(); err != nil { return err }

	rg.cov        = make(map[string]coverage, len(rg.profiles))
	units        := make([]workUnit, 0,       len(rg.profiles))
	dirsToCreate := make(map[string]struct{}) // exclude duplicate directories and keep the relatively heavy mkdir syscalls outside of the concurrent loop

	for _, profile := range rg.profiles {
		outPath := filepath.Join(rg.outRoot, profile.FileName + ".html")
		units    = append(units, workUnit{
			profile: profile,
			outPath: outPath,
		})
		dirsToCreate[filepath.Dir(outPath)] = struct{}{}
	}

	progDirs := progress.New(ctx, uint64(len(dirsToCreate)), progressOutput)
	defer progDirs.Close()

	group, gCtx := errgroup.WithContext(ctx)
	group.SetLimit(runtime.NumCPU()) // saturate available CPU threads for maximum throughput while bounding concurrent syscalls

	for dir := range dirsToCreate {
		if err := gCtx.Err(); err != nil { break } // group.Wait() below captures the error
		group.Go(func() error {
			if err := rg.fsys.MkdirAll(gCtx, dir, 0700); err != nil {
				return fmt.Errorf("cannot create directory %q: %w", dir, err)
			}
			progDirs.Report(1, "created " + dir)
			return nil
		})
	}

	if err := group.Wait(); err != nil { return err }

	progDirs.Close()
	
	// The total number of statements (cover.ProfileBlock.NumStmt) is used as a normalizing
	// proxy for work units to ensure the progress tracker accurately reflects the
	// computational effort required for files of vastly different sizes, e.g.:
	//
	//   k8s.io/kubernetes/pkg/kubelet/apis/config/register.go // contains    1 func def
	//   k8s.io/api/core/v1/generated.pb.go                    // contains 1692 func defs
	//
	// Since the global total of statements is not known a priori, dynamic discovery is
	// implemented whereby each worker goroutine calls AddTotal() as it parses a source
	// file's profiled blocks, allowing the progress tracker to refine its denominator
	// in real-time without requiring a separate pre-processing pass.

	perFileCov := make([]coverage, len(units))

	progFiles := progress.New(ctx, 0, progressOutput)
	defer progFiles.Close()

	group, gCtx = errgroup.WithContext(ctx)
	group.SetLimit(runtime.NumCPU()) // saturate available CPU threads for maximum throughput while bounding memory used by concurrent HTML buffers

	for i, unit := range units {
		if err := gCtx.Err(); err != nil { break } // group.Wait() below captures the error
		group.Go(func() error {

			var fileStatements, fileCovered int64
			for _, block := range unit.profile.Blocks {
				fileStatements += int64(block.NumStmt)
				if block.Count > 0 {
					fileCovered += int64(block.NumStmt)
				}
			}

			progFiles.AddTotal(uint64(fileStatements))

			var buf bytes.Buffer
			ew := newErrorWriter(&buf)
			if err := rg.buildCovHTML(gCtx, ew, unit.profile, unit.profile.FileName); err != nil {
				return fmt.Errorf("cannot build HTML for %q: %w", unit.profile.FileName, err)
			}

			if err := rg.fsys.WriteFile(gCtx, unit.outPath, buf.Bytes(), 0600); err != nil {
				return fmt.Errorf("cannot write HTML file for %q: %w", unit.profile.FileName, err)
			}

			progFiles.Report(float64(fileStatements), unit.profile.FileName)

			rg.totalCovered.Add(fileCovered)
			rg.totalStatements.Add(fileStatements)

			perFileCov[i] = coverage{
				covered: fileCovered,
				total:   fileStatements,
			}

			return nil
		})
	}

	err := group.Wait()

	progFiles.Close()

	for i, cov := range perFileCov {
		rg.cov[units[i].profile.FileName] = cov
	}

	return err
}

// writeTokenFragment splits fragments across newlines and resolves absolute sub-line boundaries.
func writeTokenFragment(buf *bytes.Buffer, fragment []byte, baseFileOffset int, baseClass string, blocks []*profileBlock) {
	lines          := bytes.SplitAfter(fragment, []byte("\n"))
	relativeOffset := 0

	for _, line := range lines {
		if len(line) == 0 {
			continue
		}

		hasNewline := bytes.HasSuffix(line, []byte("\n"))
		content    := line
		if hasNewline {
			content = line[:len(line) - 1]
		}

		if len(content) > 0 {
			class := baseClass
			if class == "" {
				// calculate the absolute position in the file for this whitespace line chunk
				absStart := baseFileOffset + relativeOffset
				absEnd   := absStart + len(content)
				class     = coverClass(blocks, absStart, absEnd)
			}

			if class != "" {
				buf.WriteString(`<span class="`)
				buf.WriteString(class)
				buf.WriteString(`">`)
				template.HTMLEscape(buf, content)
				buf.WriteString("</span>")
			} else {
				template.HTMLEscape(buf, content)
			}
		}

		if hasNewline {
			buf.WriteByte('\n')
		}
		relativeOffset += len(line)
	}
}

// coverClass performs an O(log n) lookup over the sorted blocks slice
// to determine the coverage state ("hit", "miss", or "") of a specified
// byte offset range [start, end].
//
// precondition: blocks must be sorted in ascending order by endOffset.
func coverClass(blocks []*profileBlock, start, end int) string {
	idx := sort.Search(len(blocks), func(i int) bool {
		return blocks[i].endOffset >= end
	})
	if idx   <  len(blocks)             &&
	   start >= blocks[idx].startOffset &&
	   end   <= blocks[idx].endOffset   {
		if blocks[idx].count > 0 {
			return "hit"
		}
		return "miss"
	}
	return ""
}

// buildCovHTML builds the HTML content for a single *.go.html file, with green (covered) and red (uncovered) lines to indicate test coverage.
func (rg *reportGenerator) buildCovHTML(ctx context.Context, ew stickyWriter, profile *cover.Profile, srcPath string) error {
	if err := ctx.Err(); err != nil { return err }

	// TODO(jbunds): refactor this method since it's ~140 lines long

	pkgPath  := filepath.Dir( profile.FileName)
	fileName := filepath.Base(profile.FileName)

	src, err := rg.fsys.ReadFile(ctx, filepath.Join(rg.pkgDirCache[pkgPath], fileName))
	if err != nil {
		return err
	}

	cssPath := strings.Repeat("../", strings.Count(srcPath, "/")) + rg.styleCSSFile
	writePreamble(ew, srcPath, cssPath)

	buf  := new(bytes.Buffer)
	scnr := new(scanner.Scanner)
	fset := token.NewFileSet()
	file := fset.AddFile(fileName, fset.Base(), len(src))
	file.SetLinesForContent(src)
	scnr.Init(file, src, nil, scanner.ScanComments)

	// it is assumed that the Go toolchain delivers profile.Blocks in sequential, ascending order
	//
	// the binary search algorithm in coverClass() relies on this sorting invariant

	var blocks []*profileBlock
	lineStarted := make(map[int]bool)

	for _, block := range profile.Blocks {
		startOffset  := 0
		startLinePos := file.LineStart(block.StartLine) // LineStart expects a 1-indexed line number
		if !lineStarted[block.StartLine] {
			startOffset = file.Offset(startLinePos) // move the start offset of the first block on this line to column 1 where a <span> tag may be placed
			lineStarted[block.StartLine] = true
		} else {
			startOffset = file.Offset(startLinePos) + (block.StartCol - 1)
		}

		endLinePos := file.LineStart(block.EndLine)
		endOffset  := file.Offset(endLinePos) + (block.EndCol - 1)

		blocks = append(blocks, &profileBlock{
			startOffset: startOffset,
			endOffset:   endOffset,
			count:       block.Count,
		})
	}

	pendingBaseOffset := 0
	pendingClass      := ""
	pendingBuf        := new(bytes.Buffer)

	flushPendingSpan := func() { // flush the accumulated token span to the main line-wrapped buffer
		if pendingBuf.Len() > 0 {
			writeTokenFragment(buf, pendingBuf.Bytes(), pendingBaseOffset, pendingClass, blocks)
			pendingBuf.Reset()
		}
	}

	lastOffset := 0

	for {
		pos, tok, lit := scnr.Scan()
		if tok == token.EOF {
			flushPendingSpan()
			if lastOffset < len(src) {
				writeTokenFragment(buf, src[lastOffset:], lastOffset, "", blocks)
			}
			break
		}

		// synchronize the token and profile block streams
		startOffset := file.Offset(pos) // convert token.File-relative token.Pos into a byte offset in src
		endOffset   := 0

		if lit == "" && tok == token.COMMENT {
			if startOffset + 2 <= len(src) &&
			   string(src[startOffset:startOffset + 2]) == "//" { // line comment
				endOffset = startOffset
				for endOffset < len(src)   &&
				    src[endOffset] != '\n' {
					endOffset++
				}
			} else { // block comment
				endOffset = startOffset
				for endOffset < len(src) - 1 {
					if src[endOffset    ] == '*' &&
					   src[endOffset + 1] == '/' {
						endOffset += 2
						break
					}
					endOffset++
				}
				if endOffset == startOffset { // safeguard
					endOffset = len(src)
				}
			}
		} else {
			endOffset = startOffset + len(lit)
		}

		if lit == "" && endOffset == startOffset {
			continue // ignore virtual tokens (e.g., inserted artificial semicolons)
		}

		coverClass := coverClass(blocks, startOffset, endOffset)

		// accumulate token bytes into the sliding window, capturing baseline tracking position before writing

		if coverClass != pendingClass {
			flushPendingSpan()
			pendingClass = coverClass
			if pendingClass != "" { // starting a covered block
				pendingBaseOffset = min(startOffset, lastOffset) // anchor base offset to include any leading whitespace
			}
		}

		if pendingClass != "" { // inside a coverage block: sequentially buffer whitespace and token
			if startOffset > lastOffset {
				pendingBuf.Write( src[lastOffset:startOffset])
			}
			pendingBuf.Write(src[startOffset:endOffset])
		} else {                // outside a coverage block: write directly to the main output buffer
			if startOffset > lastOffset {
				writeTokenFragment(buf, src[lastOffset:startOffset], lastOffset, "", blocks)
			}
			writeTokenFragment(buf, src[startOffset:endOffset], startOffset, "", blocks)
		}

		lastOffset = endOffset
	}

	for line := range bytes.SplitSeq(bytes.TrimRight(buf.Bytes(), "\n"), []byte{'\n'}) {
		ew.write(`<div class="line">`)
		ew.write(string(line))
		ew.write("</div>\n")
	}

	writePostamble(ew)
	return ew.err()
}

// writePreamble writes the preamble portion of the HTML content common to every Go source HTML file.
func writePreamble(ew stickyWriter, srcPath, cssPath string) {
	ew.write("<!DOCTYPE html>\n")
	ew.write(`<html lang="en">` + "\n")
	ew.write("<head>\n")
	ew.write(`<meta charset="utf-8">` + "\n")
	ew.write(`<link rel="stylesheet" href="`)
	ew.write(cssPath)
	ew.write(`" type="text/css">` + "\n")
	ew.write("<title>")
	ew.write(srcPath)
	ew.write("</title>\n")
	ew.write("</head>\n")
	ew.write(`<body id="code" class="line-numbers">` + "\n")
}

// writePostamble writes the postamble portion of the HTML content common to every Go source HTML file.
func writePostamble(ew stickyWriter) {
	ew.write(`<script>
try {
  const parentTheme = window.parent.document.documentElement.getAttribute('theme');
  if (parentTheme) document.documentElement.setAttribute('theme', parentTheme);
} catch (e) {
  console.warn('direct parent access blocked by browser; waiting for postMessage');
}

window.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SET_THEME') document.documentElement.setAttribute('theme', event.data.theme);
});

try {
  const parentLineNumbers = window.parent.document.documentElement.getAttribute('line-numbers');
  if (parentLineNumbers === '0') document.body.classList.remove('line-numbers');
  else document.body.classList.add('line-numbers');
} catch (e) {
  document.body.classList.add('line-numbers');
}

window.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'TOGGLE_LINE_NUMBERS') document.body.classList.toggle('line-numbers', event.data.lineNumbers);
});
</script>
</body>
</html>`)
}

// printCoverage prints per-file coverage percentages to the specified destination (typically stdout).
func (rg *reportGenerator) printCoverage(ctx context.Context, w io.Writer) error {
	if err := ctx.Err(); err != nil { return err }

	keys       := slices.Collect(maps.Keys(rg.cov))
	maxPathLen := len(slices.MaxFunc(keys, func(a, b string) int {
		return cmp.Compare(len(a), len(b))
	}))

	maxPathLen = max(maxPathLen, 5) // 5 == len("Total")

	// TODO(jeff): allow users to chose how the rows rendered in the tree should be sorted;
	//             default should probably path-depth, then alphanumerically, just like here
	slices.SortFunc(keys, func(a, b string) int {
		depthA, depthB := strings.Count(a, "/"), strings.Count(b, "/")
		if depthA != depthB { return cmp.Compare(depthA, depthB) } // sort by path depth
		return cmp.Compare(a, b)                                   // sort alphanumerically
	})

	const (
		green = "\033[32m"
		red   = "\033[31m"
	)

	divider := strings.Repeat("—", maxPathLen + 9) + "\n" // 9 == 2 spaces + len("100.00%")

	ew := newErrorWriter(w)
	ew.write("File")
	ew.write(strings.Repeat(" ", maxPathLen - 4 + 1))
	ew.write("Coverage\n")
	ew.write(divider)

	for _, path := range keys {
		cov     := rg.cov[path]
		percent := 0.0
		if cov.total > 0 {
			percent = float64(cov.covered) / float64(cov.total) * 100
		}
		ew.write(path)
		ew.write(strings.Repeat(" ", maxPathLen - len(path) + 2))
		pct       := strconv.FormatFloat(percent, 'f', 2, 64)
		colorCode := green
		if percent < 50 { colorCode = red }
		ew.write(strings.Repeat(" ", 6 - len(pct)))
		ew.writeColor(pct + "%", colorCode)
		ew.write("\n")
	}

	totalPercent    := 0.0
	totalCovered    := rg.totalCovered.Load()
	totalStatements := rg.totalStatements.Load()
	if totalStatements > 0 {
		totalPercent = float64(totalCovered) / float64(totalStatements) * 100
	}

	ew.write(divider)
	ew.write("Total")
	ew.write(strings.Repeat(" ", maxPathLen - 5 + 2))
	totalPct  := strconv.FormatFloat(totalPercent, 'f', 2, 64)
	colorCode := green
	if totalPercent < 50 { colorCode = red }
	ew.write(strings.Repeat(" ", 6 - len(totalPct)))
	ew.writeColor(totalPct + "%", colorCode)
	ew.write("\n")

	return ew.err()
}

// writeIndexHTML writes the index HTML file, which contains three template parameters (ModName, ModURL,
// and TreeHTML), and hosts one iframe within which the generated source code HTML files are rendered.
func (rg *reportGenerator) writeIndexHTML(ctx context.Context, indexHTMLFile, treeHTML string) error {
	if err := ctx.Err(); err != nil { return err }

	data := struct{
		ModName,
		ModURL,
		TreeHTML  string
	}{
		ModName:  rg.modName,
		ModURL:   rg.repoURL,
		TreeHTML: treeHTML,
	}

	return rg.writeTemplateFile(ctx, indexHTMLFile, data)
}

// writeTemplateFile writes the specified template file.
func (rg *reportGenerator) writeTemplateFile(ctx context.Context, file string, tmplVars any) error {
	if err := ctx.Err(); err != nil { return err }

	outFile   := filepath.Join(rg.outRoot, filepath.Base(file))
	tmpl, err := template.ParseFS(rg.embeddedFiles, file)
	if                                   err != nil { return fmt.Errorf("cannot parse %q: %w",     file, err) }
	f, err := rg.fsys.Create(ctx, outFile)
	if                                   err != nil { return fmt.Errorf("cannot create %q: %w", outFile, err) }
	if err := tmpl.Execute(f, tmplVars); err != nil { return fmt.Errorf("cannot render template: %w",    err) }

	return f.Close()
}

// writeStaticFiles writes the static files required by the coverage report to the user-specified path.
func (rg *reportGenerator) writeStaticFiles(ctx context.Context) error {
	if err := ctx.Err(); err != nil { return err }

	for _, file := range rg.staticFiles {
		outFile   := filepath.Join(rg.outRoot, filepath.Base(file))
		f, err    := rg.fsys.Create(ctx, outFile)
		if                                        err != nil { return fmt.Errorf("cannot create %q: %w",     outFile, err) }
		data, err := fs.ReadFile(rg.embeddedFiles, file)
		if                                        err != nil { return fmt.Errorf("cannot read %q: %w",          file, err) }
		if _, err := fmt.Fprint(f, string(data)); err != nil { return fmt.Errorf("cannot write file %q: %w", outFile, err) }
		if err := f.Close();                      err != nil { return fmt.Errorf("cannot close file %q: %w", outFile, err) }
	}

	return nil
}

// filterArgs discards any arguments up to and including "--".
func filterArgs(args []string) []string {
	for i, arg := range args {
		if arg == "--" {
			args = args[i + 1:]
			break
		}
	}
	return args
}

// isTerm determines if the specified writer is connected to a terminal.
func isTerm(v any) bool {
	if testing.Testing()                     ||
	   os.Getenv("GITHUB_ACTIONS") == "true" || // https://docs.github.com/actions/reference/workflows-and-actions/variables
	   os.Getenv("CI"            ) == "true" { return false }
	fd := getFD(v)
	if fd < 0 { return false }
	return term.IsTerminal(fd)
}

// getFD returns the file descriptor of the provided argument.
func getFD(w any) int {
	if f, ok := w.(interface{ Fd() uintptr }); ok { return int(f.Fd()) }
	return -1
}
